let num1 = 10;
let num2 = 7;

//Suma: +
let suma = num1 + num2;
console.log(suma);

//Resta: -
let resta = num1 - num2;
console.log(resta);

//Multiplicación: *
let multiplicacion = num1 * num2;
console.log(multiplicacion);

//División: /
let division = num1 / num2;
console.log(division);

//Elevación a la potencia: **
let potencia = 3 ** 4;
console.log(potencia);

//Resto: %
let resto = 10 % 3;
console.log(resto);